"""权重时序对齐：T 日信号 → T+1 生效（shift(1) + fillna(0)）。

执行层的第一道防线：策略在 T 日收盘后算出目标权重 W_T，但真正的成交发生在
T+1（开盘或收盘）。本模块把整张权重面板前移一期，使回测引擎在 T+1 读到的
是 T 日算出的目标，从时间维度上杜绝「用当日信号在当日成交」的前视偏差。
"""
from __future__ import annotations

import pandas as pd


def shift_weights(weights: pd.DataFrame) -> pd.DataFrame:
    """目标权重面板整体前移一期（T 日信号、T+1 成交），缺失日补 0。

    公式：
      W'_{t} = W_{t−1}（即 W'.shift(1)）
    前移后首行没有对应值（T 日之前无信号），用 0 填充，表示「建仓前空仓」。
    该口径与「T+1 开盘成交」的执行假设配套：T+1 开盘实际拿到的是 T 日收盘
    算出的目标权重。

    注意：这是「信号日期」的平移，不是「交易日历」的平移。若目标权重面板
    本身已经按交易日索引（无缺失交易日），shift(1) 恰好前移一个交易日；
    若面板存在跳过的交易日，则会多空出几天——本项目按连续交易日索引构建，
    不存在该问题。
    """
    return weights.shift(1).fillna(0.0)
